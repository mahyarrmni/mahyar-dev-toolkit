"""Markdown report generation (technical + strategic). Everything printed comes from stored analysis data."""
from urllib.parse import unquote, urlsplit

P = lambda u: unquote(urlsplit(u).path or "/") + (("?" + urlsplit(u).query) if urlsplit(u).query else "")


def _table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]


def _footer(b):
    m = b["meta"]
    return ["", "---", f"_Generated by ASIGE {m['engine_version']} · seed {m['seed']} · input digest `{m['inputs']['pages_digest']}`"
            f"{' · GSC digest `' + m['inputs']['gsc_digest'] + '`' if m['inputs'].get('gsc_digest') else ''} · reproducibility hash `{m.get('repro_hash', 'n/a')}`._"]


def technical_report(b) -> str:
    t, m = b["technical"], b["meta"]
    s = t["summary"]
    L = [f"# Technical SEO Report — {b['site']}", "",
         f"**Health score: {t['health_score']}/100** · {s['pages_crawled']} URLs crawled · {s['html_ok']} HTML 200 · {s['indexable']} indexable", "",
         "Score = 100 × (1 − Σ rule weight × min(1, affected / HTML pages)); weights: critical .30, high .15, medium .07, low .02.", "",
         "## Issues by severity"]
    L += _table(["Severity", "Affected URLs"], [(k, v) for k, v in s["by_severity"].items()])
    L += ["", "## Findings"]
    for i in t["issues"]:
        L += ["", f"### [{i['severity'].upper()}] {i['message']} — {i['count']} URL(s)", f"*Category: {i['category']}* · **Fix:** {i['fix']}", ""]
        L += [f"- `{P(u)}`" for u in i["urls"][:8]] + ([f"- … and {i['count'] - 8} more"] if i["count"] > 8 else [])
        if i["evidence"]:
            L.append(f"- Evidence sample: `{str({k: v for k, v in i['evidence'][0].items() if k != 'url'})[:200]}`")
    c = m.get("crawl", {})
    L += ["", "## Crawl", f"- Pages: {c.get('pages')} · errors: {c.get('errors')} · blocked by robots.txt: {c.get('blocked_by_robots')} · "
          f"elapsed {c.get('elapsed_s')} s ({c.get('pages_per_s')} pages/s)",
          f"- Budget exhausted: {c.get('budget_exhausted')} (if true, counts for orphan/broken-link rules may be incomplete)"]
    return "\n".join(L + _footer(b)) + "\n"


def strategic_report(b) -> str:
    m, recs, rm = b["meta"], b["recommendations"], b["roadmap"]
    L = [f"# SEO Strategy Report — {b['site']}", "", "## Executive summary", rm["narrative"], "",
         "## Top recommendations (priority = impact × confidence ÷ (hours + 1))"]
    L += _table(["#", "Recommendation", "Impact", "Conf.", "Hours", "Priority", "Est. clicks", "Depends on"],
                [(n + 1, r["title"], f"{r['impact']['score']} ({r['impact']['basis']})", r["confidence"]["score"], r["effort"]["hours"], r["priority"],
                  r["impact"]["est_clicks_per_period"] if r["impact"]["est_clicks_per_period"] is not None else "n/a", ", ".join(r["dependencies"]) or "-")
                 for n, r in enumerate(recs[:12])])
    tp = b.get("topical")
    if tp:
        L += ["", "## Topical authority", "Authority = weighted mean of available components (coverage .35, depth .25, cohesion .20, performance .20)."]
        L += _table(["Topic", "Pages", "Authority", "Components", "Pillar"], [(x["label"], x["details"]["pages"], x["authority"], x["components"], P(x["pillar"])) for x in tp["topics"][:10]])
        if tp["gaps"]:
            L += ["", "### Content gaps"] + _table(["Gap", "Impressions", "Example queries", "Format"], [(g["label"], int(g["impressions"]), ", ".join(q[0] for q in g["queries"][:3]), g["suggested_format"]) for g in tp["gaps"][:8]])
    cn = b.get("cannibalization")
    if cn and "n_queries" in cn[0]:
        L += ["", "## Keyword cannibalization (GSC evidence)"] + _table(["Pages", "Queries", "Impressions", "Similarity", "Dispersion", "Action"],
              [(", ".join(P(u) for u in c["pages"]), c["n_queries"], int(c["impressions"]), c["semantic_similarity"], c["dispersion"], c["action"]) for c in cn[:8]])
    elif cn:
        L += ["", "## Potential cannibalization (crawl-only, no GSC evidence: lower confidence)"] + _table(
            ["Pages", "Semantic similarity", "Title overlap"], [(", ".join(P(u) for u in c["pages"]), c["semantic_similarity"], c["title_jaccard"]) for c in cn[:8]])
    lk = b["linking"]
    L += ["", "## Internal linking", f"- {lk['stats']['pages']} indexable pages, {lk['stats']['edges']} internal links, {lk['stats']['orphans']} orphans, max click depth {lk['stats']['max_depth']}."]
    sim = lk.get("simulation")
    if sim:
        L += [f"- Simulation (top {sim['edges_added']} suggestions): mean target PageRank {sim['mean_target_pagerank_change_pct']:+}%, orphans {sim['orphans_before']}→{sim['orphans_after']}, mean depth {sim['mean_depth_before']}→{sim['mean_depth_after']}."]
    L += _table(["From", "To", "Anchor", "Score"], [(P(s["source"]), P(s["target"]), s["evidence"]["anchor"], s["score"]) for s in lk["suggestions"][:10]])
    pr = b.get("predictive")
    if pr:
        L += ["", "## Predictive analytics", f"CTR curve source: **{pr['curve_source']}**" + (" (generic prior — import more GSC data for a site-specific curve)" if pr["curve_source"] != "site_gsc" else "")]
        if pr.get("cross_validation"):
            L += [f"- Cross-validated WAPE (lower is better): {pr['cross_validation']['wape']}", f"- GBM permutation importance: {pr['cross_validation'].get('gbm_permutation_importance')}"]
        L += _table(["Scenario", "Rows", "Baseline clicks", "Projected extra clicks", "90% interval"], [(s["name"], s["rows"], s["baseline_clicks"], s["projected_extra_clicks"], s["interval_90"] or "n/a") for s in pr["scenarios"]])
    cp = b.get("competitor")
    if cp and cp.get("topic_gaps"):
        L += ["", "## Competitor intelligence", f"Topic coverage vs competitor: {cp['topic_gaps']['coverage']}"] + [f"- {g['label']} ({g['n_pages']} pages)" for g in cp["topic_gaps"]["gaps"][:6]]
    L += ["", "## Roadmap"] + _table(["Week", "Hours", "Tasks"], [(s["week"], s["planned_hours"], "; ".join(rm["tasks"][t["id"]]["title"] + (" ✔" if t["finishes"] else "") for t in s["tasks"])) for s in rm["schedule"]])
    L += ["", f"_{rm['totals']['est_clicks_note']}_", "", "## Method & limitations",
          "- Recommendations are rule/model outputs with provenance (see JSON `provenance` per item); no LLM generates findings.",
          "- Click estimates use the CTR curve and explicit recovery-rate assumptions; they are projections, not guarantees.",
          "- Entity extraction is heuristic (no pretrained NER); LSA embeddings are monolingual per script unless the SBERT backend is enabled."]
    return "\n".join(L + _footer(b)) + "\n"
